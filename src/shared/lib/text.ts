/**
 * Разбивает строку на отдельные символы, чтобы каждую букву
 * можно было анимировать по отдельности.
 *
 * @param text - исходная строка.
 * @returns массив символов исходной строки.
 */
export const getLetters = (text: string): string[] => text.split('');

/**
 * Заменяет обычный пробел на неразрывный (nbsp), чтобы пробелы
 * корректно отображались в ряду анимированных букв заголовка.
 *
 * @param letter - символ строки.
 * @returns неразрывный пробел для пробела, иначе исходный символ.
 */
export const replaceSpaceWithNbsp = (letter: string): string =>
  letter === ' ' ? '\u00A0' : letter;
